#!/usr/bin/env python3
"""impulse: binary -> C header (drop-in for `xxd -i`, which is not
POSIX and not present on stock macOS / MSYS2).

Usage: bin2h.py <input-binary> <output-header>

Symbol naming matches xxd: the input basename with non-alphanumerics
mapped to '_' (session.bin -> session_bin / session_bin_len).
"""
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <input-binary> <output-header>", file=sys.stderr)
        return 1
    inp, out = sys.argv[1], sys.argv[2]
    data = open(inp, "rb").read()
    name = "".join(c if c.isalnum() else "_" for c in inp.rsplit("/", 1)[-1])
    with open(out, "w") as f:
        f.write(f"/* generated by scripts/bin2h.py from {inp.rsplit('/', 1)[-1]} */\n")
        f.write(f"unsigned char {name}[] = {{\n")
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",\n")
        f.write("};\n")
        f.write(f"unsigned int {name}_len = {len(data)};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
